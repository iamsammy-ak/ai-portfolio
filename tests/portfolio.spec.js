import { test, expect } from '@playwright/test'

test('readable profile, project search, calculator and CV work under a subdirectory', async ({ page, request }) => {
  const errors = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('./?plain')
  await expect(page.getByRole('heading', { name: 'Technical depth. Human impact.' })).toBeVisible()
  await expect(page.locator('.featured-project')).toHaveCount(6)
  await page.getByRole('searchbox').fill('semantic-cache')
  await expect(page.locator('.project-directory > a')).toHaveCount(1)
  await expect(page.locator('.project-directory > a')).toHaveAttribute('href', 'https://github.com/iamsammy-ak/semantic-cache-gateway')
  await page.getByRole('searchbox').fill('nothing-matches-this')
  await expect(page.locator('.empty-state')).toBeVisible()
  await expect(page.locator('.lab-result')).toContainText('5.0')
  await page.getByRole('slider', { name: 'Human review time' }).press('End')
  await expect(page.locator('.lab-result')).toContainText('Additional time required')
  expect((await request.get('./Abhishek_Kumar_CV.pdf')).headers()['content-type']).toBe('application/pdf')
  expect(errors).toEqual([])
  await page.screenshot({ path: 'artifacts/profile-desktop.png', fullPage: true })
})

