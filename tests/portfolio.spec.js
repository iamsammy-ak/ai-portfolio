test('original world loads locally, travels and navigates to the project chapter', async ({ page }) => {
  const errors = [], failures = [], external = []
  page.on('pageerror', e => errors.push(e.stack))
  page.on('response', r => { if(r.status() >= 400) failures.push(r.url()) })
  page.on('request', r => { if(r.url().startsWith('https://')) external.push(r.url()) })
  await page.goto('./')
  await expect(page.getByRole('button', { name: 'Explore my world' })).toBeEnabled({ timeout: 60000 })
  await page.getByRole('button', { name: 'Explore my world' }).click()
  await page.waitForTimeout(3500)
  await expect(page.getByRole('heading', { name: 'AI works when people can use it.' })).toBeVisible()
  const world = page.frames().find(f => f.url().includes('/world/'))
  const readScroll = () => world.evaluate(async () => (await import('./assets/index-DjXkBzPf.js')).aN.getState().scroll)
  const start = await readScroll()
  await page.getByRole('button', { name: 'Travel forward' }).click()
  await expect.poll(readScroll).toBeGreaterThan(start + .005)
  await page.screenshot({ path: 'artifacts/world-desktop.png' })
  await page.getByRole('button', { name: 'The evidence', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Useful AI, with the evidence attached.' })).toBeVisible({ timeout: 15000 })
  await page.waitForTimeout(2500)
  await page.screenshot({ path: 'artifacts/world-projects.png' })
  expect(errors).toEqual([]); expect(failures).toEqual([]); expect(external).toEqual([])
  await page.getByRole('button', { name: 'Explore the GitHub projects' }).click()
  await expect(page.locator('#projects')).toBeVisible()
})

