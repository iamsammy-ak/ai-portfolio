import { test, expect } from '@playwright/test'

test('original loader and world use personal CV and GitHub content', async ({ page, request }) => {
  const errors = [], failures = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('response', response => { if (response.status() >= 400) failures.push(response.url()) })
  await page.goto('./?plain')
  const world = page.frameLocator('iframe')
  await expect(world.locator('.motorbike img')).toHaveAttribute('src', 'image/motorbike.png')
  await expect(world.getByRole('link', { name: 'start', exact: true })).toBeVisible({ timeout: 60000 })
  await page.screenshot({ path: 'artifacts/original-loader.png' })
  await world.getByRole('link', { name: 'start', exact: true }).click()
  await expect(world.locator('.main-title h1')).toContainText('Abhishek', { timeout: 15000 })
  await page.waitForTimeout(3500)
  await page.screenshot({ path: 'artifacts/original-home.png' })
  const frame = page.frames().find(f => f.url().includes('/world/'))
  await frame.locator('body').click({ position: { x: 100, y: 200 } })
  await frame.locator('body').press('ArrowDown')
  await expect.poll(() => frame.evaluate(async () => (await import('./assets/index-DjXkBzPf.js')).aN.getState().scroll)).toBeGreaterThan(.005)
  await world.locator('.burger-wrapper').click()
  await world.getByRole('button', { name: 'about', exact: true }).click()
  await expect.poll(() => frame.evaluate(async () => (await import('./assets/index-DjXkBzPf.js')).aM.getState().country)).toBe('frlux')
  await expect(world.locator('.fr-text-content')).toContainText('OpenSky VR Italia')
  await expect(world.locator('.fr-text-content a').first()).toHaveAttribute('href', '../Abhishek_Kumar_CV.pdf')
  await world.locator('.burger-wrapper').click()
  await world.getByRole('button', { name: 'projects', exact: true }).click()
  await expect.poll(() => frame.evaluate(async () => (await import('./assets/index-DjXkBzPf.js')).aM.getState().country)).toMatch(/^lux(?:be)?$/)
  await expect(world.locator('a[href="https://github.com/iamsammy-ak/mynotebooklm"]')).toHaveCount(1)
  await page.waitForTimeout(2500)
  await page.screenshot({ path: 'artifacts/original-projects.png' })
  await world.locator('.burger-wrapper').click()
  await world.getByRole('button', { name: 'contact', exact: true }).click()
  await expect.poll(() => frame.evaluate(async () => (await import('./assets/index-DjXkBzPf.js')).aM.getState().country)).toBe('befr')
  await expect(world.getByRole('button', { name: 'My GitHub', exact: true })).toBeVisible()
  expect((await request.get('./Abhishek_Kumar_CV.pdf')).status()).toBe(200)
  expect(await page.locator('body').innerText()).not.toMatch(/coach|scenic route|Read profile/i)
  expect(errors).toEqual([]); expect(failures).toEqual([])
})

test('mobile keeps the original opening and starts the same world', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('./')
  const world = page.frameLocator('iframe')
  await expect(world.getByRole('link', { name: 'start', exact: true })).toBeVisible({ timeout: 60000 })
  await world.getByRole('link', { name: 'start', exact: true }).click()
  await page.waitForTimeout(3500)
  await expect(world.locator('.main-title h1')).toContainText('Abhishek')
  await page.screenshot({ path: 'artifacts/original-mobile.png' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
})
